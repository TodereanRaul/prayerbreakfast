// Turns src/data/seed.json into supabase/seed.sql.
// Usage: node scripts/generate-seed-sql.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
const seed = JSON.parse(readFileSync(new URL("src/data/seed.json", root), "utf8"));

const lit = (v) =>
  v === undefined || v === null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replaceAll("'", "''")}'`;

const eventCols = [
  "title", "short_name", "city", "country", "country_code", "venue", "year", "month",
  "start_date", "end_date", "date_note", "status", "description", "image_query",
  "image_url", "image_credit", "image_source_url",
];
const eventRows = seed.events.map(
  (e) => `  (${eventCols.map((c) => (c === "status" ? lit(e.status ?? "confirmed") : lit(e[c]))).join(", ")})`,
);

const nationCols = ["country", "country_code", "status", "note", "sort_order"];
const nationRows = seed.nations.map(
  (n, i) => `  (${nationCols.map((c) => (c === "sort_order" ? String(i) : lit(n[c]))).join(", ")})`,
);

const sql = `-- Generated by scripts/generate-seed-sql.mjs from src/data/seed.json
-- Source: ${seed._source}
-- City photos come from Wikipedia (npm run seed:images); admins can replace them.

insert into public.events (${eventCols.join(", ")}) values
${eventRows.join(",\n")};

insert into public.nations (${nationCols.join(", ")}) values
${nationRows.join(",\n")};
`;

const out = new URL("supabase/seed.sql", root);
writeFileSync(out, sql);
console.log(`Wrote ${fileURLToPath(out)} (${eventRows.length} events, ${nationRows.length} nations)`);
